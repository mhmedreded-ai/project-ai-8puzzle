"""
heuristics.py: Academic Heuristic Functions for the 8-Puzzle.

This module provides two canonical admissible heuristics:
1. Misplaced Tiles (Hamming Distance h1)
2. Manhattan Distance (Taxicab / L1 Metric h2)

Theoretical Properties:
-----------------------
- Admissibility:
    A heuristic h(n) is admissible if for every state n:
        0 <= h(n) <= h*(n)
    where h*(n) is the true optimal cost to reach the goal from state n.
    Both h1 and h2 are admissible.

- Consistency (Monotonicity):
    A heuristic h(n) is consistent if for every node n and successor n' generated by action a:
        h(n) <= c(n, a, n') + h(n')
    where c(n, a, n') = 1 is the step cost.
    Consistency implies admissibility and guarantees that graph search with a closed
    list finds the optimal path without re-opening nodes.

- Dominance:
    For any two admissible heuristics h1 and h2, h2 dominates h1 if:
        forall n: h2(n) >= h1(n)
    Since every misplaced tile has a Manhattan distance >= 1, h2(n) >= h1(n) holds
    for every state n. Dominance guarantees that A* with h2 expands no more nodes
    than A* with h1 (up to tie-breaking).
"""

from __future__ import annotations
from typing import Callable
from src.puzzle import State, GOAL_STATE

# Type alias for heuristic function
HeuristicFn = Callable[[State, State], int]

# Precompute 2D coordinates (row, col) for all 9 1D indices for maximum performance
_INDEX_TO_COORD: tuple[tuple[int, int], ...] = tuple(
    (idx // 3, idx % 3) for idx in range(9)
)

# Precomputed mapping from tile value -> (row, col) in canonical GOAL_STATE
# Goal layout:
# 1(0,0)  2(0,1)  3(0,2)
# 4(1,0)  5(1,1)  6(1,2)
# 7(2,0)  8(2,1)  0(2,2)
_CANONICAL_GOAL_COORDS: dict[int, tuple[int, int]] = {
    tile: _INDEX_TO_COORD[idx]
    for idx, tile in enumerate(GOAL_STATE)
    if tile != 0
}


def misplaced_tiles(state: State, goal: State = GOAL_STATE) -> int:
    """
    Heuristic h1: Misplaced Tiles (Hamming Distance).

    Counts the number of non-blank tiles (1 through 8) that are not currently
    occupying their goal positions.

    Mathematical Definition:
        h1(n) = sum_{t in {1..8}} [ 1 if pos_state(t) != pos_goal(t) else 0 ]

    Admissibility Proof:
        Moving one tile requires 1 move and can at most place that single tile into
        its goal position. Therefore, if k tiles are out of place, at least k moves
        must be executed. Thus, h1(n) <= h*(n).

    Consistency Proof:
        A single move transitions one tile into an adjacent cell. This move can
        either place the tile into its goal position (h1 decreases by 1), move it
        out of its goal position (h1 increases by 1), or leave its misplaced status
        unchanged. Thus, |h1(n) - h1(n')| <= 1 = c(n, a, n'), which satisfies
        the triangle inequality h1(n) <= c(n, a, n') + h1(n').

    Args:
        state: Current 9-tuple board state.
        goal: Target goal state (defaults to canonical GOAL_STATE).

    Returns:
        int: Count of misplaced non-blank tiles.
    """
    count = 0
    for s_val, g_val in zip(state, goal):
        if s_val != 0 and s_val != g_val:
            count += 1
    return count


def manhattan_distance(state: State, goal: State = GOAL_STATE) -> int:
    """
    Heuristic h2: Manhattan Distance (Taxicab / L1 Metric).

    Computes the sum of horizontal and vertical distances of each non-blank tile
    from its target coordinate in the goal state.

    Mathematical Definition:
        h2(n) = sum_{t in {1..8}} ( |r_state(t) - r_goal(t)| + |c_state(t) - c_goal(t)| )

    Admissibility Proof:
        Consider a relaxed problem where tiles can move horizontally and vertically
        even if the destination cell is already occupied. In this relaxed problem,
        the minimum number of steps required to move tile t to its goal is its
        Manhattan distance. Since real moves are constrained by blank occupancy,
        the true cost h*(n) cannot be smaller than the relaxed cost.
        Thus, h2(n) <= h*(n).

    Consistency Proof:
        In each legal move, exactly one non-blank tile changes its position by 1
        unit in one coordinate direction. This changes that tile's Manhattan distance
        to its goal by at most +1 or -1, while all other tiles remain fixed.
        Consequently, h2(n) - h2(n') <= 1 = c(n, a, n'), ensuring consistency.

    Dominance over h1:
        For every non-blank tile t:
          - If t is in its goal position, both its misplaced count and Manhattan distance are 0.
          - If t is misplaced, its Manhattan distance is at least 1 (|dr| + |dc| >= 1).
        Summing over all tiles yields:
            forall n: h2(n) >= h1(n).
        Since h2 is admissible and dominates h1, A* with h2 expands a subset of
        the nodes expanded by A* with h1 (excluding ties).

    Args:
        state: Current 9-tuple board state.
        goal: Target goal state (defaults to canonical GOAL_STATE).

    Returns:
        int: Sum of Manhattan distances for tiles 1 through 8.
    """
    # Optimized path for canonical goal state using precomputed coordinates
    if goal == GOAL_STATE:
        total_dist = 0
        for idx, tile in enumerate(state):
            if tile != 0:
                cur_r, cur_c = _INDEX_TO_COORD[idx]
                goal_r, goal_c = _CANONICAL_GOAL_COORDS[tile]
                total_dist += abs(cur_r - goal_r) + abs(cur_c - goal_c)
        return total_dist

    # General arbitrary goal path
    goal_coords = {
        tile: _INDEX_TO_COORD[idx]
        for idx, tile in enumerate(goal)
        if tile != 0
    }
    total_dist = 0
    for idx, tile in enumerate(state):
        if tile != 0:
            cur_r, cur_c = _INDEX_TO_COORD[idx]
            goal_r, goal_c = goal_coords[tile]
            total_dist += abs(cur_r - goal_r) + abs(cur_c - goal_c)
    return total_dist

